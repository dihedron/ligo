var (
	png   = []byte("\x89PNG\r\n\x1a\nrest")
	svg   = []byte(`<?xml version="1.0"?><svg xmlns="http://www.w3.org/2000/svg"/>`)
	ico   = []byte{0, 0, 1, 0, 1}
	woff2 = []byte("wOF2rest")
)

func write(t *testing.T, path string, data []byte) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, data, 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.Chmod(path, 0o644); err != nil { // the umask may have dropped bits; set exactly
		t.Fatal(err)
	}
}

func me() Options { return Options{OwnerUID: uint32(os.Getuid())} } //nolint:gosec // a uid fits

// TestLoadConventional: the conventional files of the directory, the first
// extension in order when two exist, fonts, and the WARNs for duplicates
// and remote references; nothing is required.
func TestLoadConventional(t *testing.T) {
	if th, err := Load(Files{Directory: filepath.Join(t.TempDir(), "none")}, me()); err != nil || len(th.Hashes()) != 0 {
		t.Fatalf("no theme directory: %v %v", th, err)
	}
	dir := t.TempDir()
	write(t, filepath.Join(dir, "theme.css"), []byte(`body { background: url("bg.png"); } @import url(https://fonts.example/x.css);`))
	write(t, filepath.Join(dir, "logo.svg"), svg)
	write(t, filepath.Join(dir, "logo.png"), png)
	write(t, filepath.Join(dir, "logo-dark.png"), png)
	write(t, filepath.Join(dir, "favicon.ico"), ico)
	write(t, filepath.Join(dir, "fonts", "brand.woff2"), woff2)
	var logs bytes.Buffer
	opts := me()
	opts.Logger = slog.New(slog.NewTextHandler(&logs, nil))
	th, err := Load(Files{Directory: dir}, opts)
	if err != nil {
		t.Fatal(err)
	}
	if th.Logo.ContentType != "image/svg+xml" || th.LogoDark.ContentType != "image/png" || th.Favicon.ContentType != "image/x-icon" ||
		th.CSS.ContentType != "text/css; charset=utf-8" || th.Fonts["brand.woff2"] == nil || th.Tokens != nil {
		t.Errorf("theme: %+v", th)
	}
	if h := th.Hashes(); len(h) != 5 || h["fonts/brand.woff2"] != sum(woff2) || h["logo"] != sum(svg) {
		t.Errorf("hashes: %v", h)
	}
	for _, want := range []string{"several files for one element", "remote resource"} {
		if !strings.Contains(logs.String(), want) {
			t.Errorf("no WARN %q in %s", want, logs.String())
		}
	}
	if strings.Count(logs.String(), "remote resource") != 2 { // the @import and its url(https://…); url("bg.png") is relative
		t.Errorf("remote references: %s", logs.String())
	}
}

// TestLoadRefuses: rule 15's failures, each naming the file.
func TestLoadRefuses(t *testing.T) {
	dir := t.TempDir()
	write(t, filepath.Join(dir, "fake.png"), []byte("GIF89a"))
	write(t, filepath.Join(dir, "logo.jpg"), png)
	write(t, filepath.Join(dir, "big.css"), bytes.Repeat([]byte("a"), maxCSS+1))
	write(t, filepath.Join(dir, "open.svg"), svg)
	if err := os.Chmod(filepath.Join(dir, "open.svg"), 0o666); err != nil {
		t.Fatal(err)
	}
	write(t, filepath.Join(dir, "ok.svg"), svg)
	for _, c := range []struct {
		name  string
		files Files
		opts  Options
		want  string
	}{
		{"missing explicit file", Files{CSS: filepath.Join(dir, "none.css")}, me(), "none.css"},
		{"extension not allowed", Files{Logo: filepath.Join(dir, "logo.jpg")}, me(), "extension"},
		{"content does not match", Files{Favicon: filepath.Join(dir, "fake.png")}, me(), "content does not match"},
		{"too large", Files{CSS: filepath.Join(dir, "big.css")}, me(), "at most"},
		{"writable by others", Files{Logo: filepath.Join(dir, "open.svg")}, me(), "writable"},
		{"another owner", Files{Logo: filepath.Join(dir, "ok.svg")}, Options{OwnerUID: uint32(os.Getuid()) + 1}, "owned by"}, //nolint:gosec // a uid fits
		{"missing fonts_dir", Files{Fonts: filepath.Join(dir, "nofonts")}, me(), "fonts_dir"},
	} {
		c.files.Directory = filepath.Join(dir, "empty")
		if _, err := Load(c.files, c.opts); err == nil || !strings.Contains(err.Error(), c.want) || !strings.HasPrefix(err.Error(), "rule 15: ") {
			t.Errorf("%s: %v", c.name, err)
		}
	}
	fonts := filepath.Join(dir, "fonts")
	for i := range maxFonts + 1 {
		write(t, filepath.Join(fonts, strconv.Itoa(i)+".woff2"), woff2)
	}
	if _, err := Load(Files{Directory: filepath.Join(dir, "empty"), Fonts: fonts}, me()); err == nil || !strings.Contains(err.Error(), "at most 16") {
		t.Errorf("17 fonts: %v", err)
	}
}

// TestTokensCSS: ui.theme.colors becomes tokens.css, light on :root and
// dark under both dark selectors; a low contrast is a WARN.
func TestTokensCSS(t *testing.T) {
	var logs bytes.Buffer
	opts := me()
	opts.Logger = slog.New(slog.NewTextHandler(&logs, nil))
	th, err := Load(Files{Directory: t.TempDir(), Colors: map[string]map[string]string{
		"light": {"primary": "#1f4e8c", "text": "#aaaaaa"}, "dark": {"primary": "#8fb4e8"}}}, opts)
	if err != nil {
		t.Fatal(err)
	}
	want := `/* generated by ligo from ui.theme.colors (§7.6) */
:root {
  --color-primary: #1f4e8c;
  --color-text: #aaaaaa;
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    --color-primary: #8fb4e8;
  }
}
:root[data-theme="dark"] {
  --color-primary: #8fb4e8;
}
`
	if th.Tokens == nil || string(th.Tokens.Data) != want || th.Hashes()["tokens.css"] != sum([]byte(want)) {
		t.Errorf("tokens.css:\n%s", th.Tokens.Data)
	}
	if out := logs.String(); !strings.Contains(out, "contrast below WCAG AA") || !strings.Contains(out, "--color-text") ||
		strings.Contains(out, "mode=dark") {
		t.Errorf("contrast WARN: %s", out)
	}
}
