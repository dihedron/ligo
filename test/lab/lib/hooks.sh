#!/usr/bin/env bash
# The webhook scenario: a receiver in its own container, which checks the
# signatures of ligo's notifications and records them (§7.5, §11.1,
# .specs/ligo-test-environment.md, "The webhook receiver hooks").

HOOKS_PORT=8443
HOOKS_LOG=/var/lib/webhook-receiver/events.jsonl
HOOKS_UNIT=webhook-receiver
HOOKS_NAMES=(oncall dba elsewhere)

# hooks_secret NAME: a webhook's HMAC secret, created once.
hooks_secret() {
	local file="$LAB_STATE_DIR/passwords/hook-$1"
	[[ -f "$file" ]] || (umask 077 && openssl rand -hex 32 >"$file")
	cat "$file"
}

hooks_unit() {
	cat <<UNIT
# lab: generated by test/lab/lab.sh (lib/hooks.sh)
[Unit]
Description=The lab's webhook receiver
After=network-online.target

[Service]
User=hooks
StateDirectory=webhook-receiver
EnvironmentFile=/etc/webhook-receiver/env
ExecStart=/usr/local/bin/webhook-receiver -listen :$HOOKS_PORT -cert /etc/webhook-receiver/hooks.crt -key /etc/webhook-receiver/hooks.key -log $HOOKS_LOG
Restart=on-failure

[Install]
WantedBy=multi-user.target
UNIT
}

# hooks_up: the container hooks with the receiver, its certificate, secrets and
# unit.
hooks_up() {
	section "Webhook receiver"
	inner_container hooks "$LAB_HOOKS_MEMORY"
	pki_issue hooks "DNS:hooks.ligo.lab,IP:$(inner_ip hooks)"
	local bin="$LAB_STATE_DIR/webhook-receiver" name
	(cd "$REPO_DIR" && CGO_ENABLED=0 GOOS=linux GOARCH=amd64 go build -o "$bin" ./test/lab/webhook-receiver) || die "cannot build the webhook receiver"
	inner_exec hooks systemctl stop "$HOOKS_UNIT" 2>/dev/null || true
	inner_push "$bin" hooks /usr/local/bin/webhook-receiver 0755
	inner_exec hooks sh -c 'id hooks >/dev/null 2>&1 || useradd --system --no-create-home hooks; install -d -o root -g hooks -m 0750 /etc/webhook-receiver'
	inner_push "$LAB_STATE_DIR/pki/hooks.crt" hooks /etc/webhook-receiver/hooks.crt 0644
	inner_push "$LAB_STATE_DIR/pki/hooks.key" hooks /etc/webhook-receiver/hooks.key 0640
	for name in "${HOOKS_NAMES[@]}"; do
		printf 'HOOK_SECRET_%s=%s\n' "$(tr '[:lower:]' '[:upper:]' <<<"$name")" "$(hooks_secret "$name")"
	done | inner_exec hooks sh -c 'umask 027 && cat >/etc/webhook-receiver/env'
	inner_exec hooks chgrp hooks /etc/webhook-receiver/hooks.key /etc/webhook-receiver/env
	hooks_unit | inner_exec hooks sh -c "cat >/etc/systemd/system/$HOOKS_UNIT.service"
	inner_exec hooks sh -c "systemctl daemon-reload; systemctl enable $HOOKS_UNIT >/dev/null 2>&1; systemctl restart $HOOKS_UNIT"
	sleep 1
	inner_exec hooks systemctl is-active --quiet "$HOOKS_UNIT" || die "hooks: the receiver does not run: lab.sh logs hooks $HOOKS_UNIT"
	env_set .hooks "$(jq -n --arg ip "$(inner_ip hooks)" '{address: $ip}')"
	info "hooks: the receiver takes webhooks with TLS on hooks.ligo.lab:$HOOKS_PORT"
}

# hooks_env: ligo's side of the secrets, for its environment file.
hooks_env() {
	inner_exists hooks || return 0
	local name
	for name in "${HOOKS_NAMES[@]}"; do
		printf 'LIGO_WEBHOOK_%s_SECRET=%s\n' "$(tr '[:lower:]' '[:upper:]' <<<"$name")" "$(hooks_secret "$name")"
	done
}

# hooks_notifications: server.yaml's webhooks: oncall has no filter; dba is
# filtered on the ledger's scope, which the tests' changes match; elsewhere on
# a scope nothing in the lab has, so it receives system events only.
hooks_notifications() {
	inner_exists hooks || return 0
	local events='[BREAK_GLASS_USED, CR_AWAITING_APPROVAL, BINDING_REVOKED, SYSTEM_MAINTENANCE_ENABLED, SYSTEM_MAINTENANCE_DISABLED, SYSTEM_EXECUTOR_RECOVERED]'
	local dba="dc/corp-prod/ledger" elsewhere="dc/elsewhere/*"
	if [[ -n "$LAB_ACCOUNTS" ]]; then # TN-12: the target's account hears, the source's does not
		events="${events%]}, BINDING_TARGET_DECIDED_BY_PLATFORM]" dba="tenants/globex/*" elsewhere="tenants/acme/*"
	fi
	local common="ca_cert_file: /etc/ligo-lab/ca.crt, timeout: 5s, events: $events"
	cat <<YAML
notifications:
  webhooks:
    - { name: oncall, url: "https://hooks.ligo.lab:$HOOKS_PORT/hooks/oncall", hmac_secret_env: LIGO_WEBHOOK_ONCALL_SECRET, $common }
    - { name: dba, url: "https://hooks.ligo.lab:$HOOKS_PORT/hooks/dba", hmac_secret_env: LIGO_WEBHOOK_DBA_SECRET, scopes: ["$dba"], $common }
    - { name: elsewhere, url: "https://hooks.ligo.lab:$HOOKS_PORT/hooks/elsewhere", hmac_secret_env: LIGO_WEBHOOK_ELSEWHERE_SECRET, scopes: ["$elsewhere"], $common }
YAML
}

# hooks_count EVENT: how many EVENT the receiver recorded, whatever the webhook.
hooks_count() {
	inner_exec hooks cat "$HOOKS_LOG" | jq -s --arg e "$1" '[.[].body | fromjson | select(.event == $e)] | length'
}

# hooks_pending: the outbox rows still to be delivered.
hooks_pending() { serve_sql "select count(*) from notification_outbox where delivered_at is null and abandoned_at is null"; }

# hooks_drained: waits for the outbox to empty; a row that failed once waits
# 10s, one that failed twice 20s.
hooks_drained() {
	local _
	for _ in $(seq 1 90); do
		[[ "$(hooks_pending)" == 0 ]] && return
		sleep 1
	done
	serve_sql "select webhook, event, attempts, last_error from notification_outbox where delivered_at is null and abandoned_at is null" >&2
	die "the outbox did not empty in 90s"
}

# hooks_abandoned: the sum of ligo_notifications_abandoned_total on the replicas.
hooks_abandoned() {
	local host sum=0 n
	for host in $(ligo_hosts); do
		n="$(inner_exec "$host" curl -fsS http://127.0.0.1:9090/metrics | awk '/^ligo_notifications_abandoned_total/ { s += $2 } END { print s + 0 }')"
		sum=$((sum + n))
	done
	echo "$sum"
}

# serve_test_webhook: the receiver's scenarios (§7.5, AC-31, AC-37, AC-70):
# delivery and scope filters; the receiver down, then back; a row abandoned
# after 24h; each replica alone delivering. Finally TestServeWebhookFile checks
# everything the receiver recorded.
serve_test_webhook() {
	inner_exists hooks || die "serve test-webhook needs the receiver: lab.sh up --scenario webhook"
	inner_exec ligo1 grep -q '^notifications:' /etc/ligo/server.yaml || die "ligo has no webhooks configured: lab.sh serve install"
	[[ "$(ligo_hosts | xargs)" == "ligo1 ligo2" ]] || die "serve test-webhook needs ligo2: lab.sh up --scenario ha"
	deploy_tests
	section "Webhooks of ligo serve"
	E2E_SUFFIX="$(openssl rand -hex 4)"
	serve_admins
	# rows of an earlier run reach an empty log before this one starts
	serve_sql "update notification_outbox set next_attempt_at = now() where delivered_at is null and abandoned_at is null" >/dev/null
	hooks_drained
	inner_exec hooks truncate -s 0 "$HOOKS_LOG"

	serve_e2e '^TestServeWebhookEvents$' ligo1 ligo2 || die "TestServeWebhookEvents failed"
	hooks_drained
	info "the events reached the receiver"

	section "The receiver down, then back (AC-37)"
	inner_exec hooks systemctl stop "$HOOKS_UNIT"
	serve_e2e '^TestServeWebhookDown$' ligo1 ligo2 || die "TestServeWebhookDown failed"
	local failed="select event_id from notification_outbox where webhook = 'oncall' and event = 'BREAK_GLASS_USED' and payload->'resource'->>'name' = 'hook-down-$E2E_SUFFIX' and delivered_at is null and attempts >= 1 and last_error is not null"
	local id="" _
	for _ in $(seq 1 30); do
		id="$(serve_sql "$failed")"
		[[ -n "$id" ]] && break
		sleep 1
	done
	[[ -n "$id" ]] || die "no failed attempt in the outbox with the receiver down"
	inner_exec hooks systemctl start "$HOOKS_UNIT"
	hooks_drained
	local out
	out="$(inner_exec hooks cat "$HOOKS_LOG")"
	grep "$id" <<<"$out" >/dev/null || die "the event $id did not arrive under its original eventId"
	info "the change applied with the receiver down; event $id arrived after it came back"

	section "A row abandoned after 24h (AC-37)"
	inner_exec hooks systemctl stop "$HOOKS_UNIT"
	local before after abandoned
	before="$(hooks_abandoned)"
	serve_e2e '^TestServeWebhookMaintenance$' ligo1 ligo2 || die "TestServeWebhookMaintenance failed"
	local aged="update notification_outbox set created_at = now() - interval '25 hours', next_attempt_at = now() where delivered_at is null and abandoned_at is null returning event_id"
	local ids
	ids="$(serve_sql "$aged" | grep -v '^UPDATE')" # psql -tA prints the command tag too
	abandoned="$(wc -l <<<"$ids")"
	((abandoned == 6)) || die "aged $abandoned rows, not 6: two events, three webhooks"
	for _ in $(seq 1 30); do
		[[ "$(hooks_pending)" == 0 ]] && break
		sleep 1
	done
	[[ "$(hooks_pending)" == 0 ]] || die "the aged rows were not abandoned in 30s"
	[[ "$(serve_sql "select count(*) from notification_outbox where abandoned_at is not null and last_error is not null and event_id::text in ($(sed "s/.*/'&'/" <<<"$ids" | paste -sd,))")" == "$abandoned" ]] ||
		die "the aged rows are not all marked abandoned, with their error"
	after="$(hooks_abandoned)"
	((after - before == abandoned)) || die "ligo_notifications_abandoned_total rose by $((after - before)), not $abandoned"
	inner_exec hooks systemctl start "$HOOKS_UNIT"
	sleep 10 # nothing may deliver them once the receiver is back
	out="$(inner_exec hooks cat "$HOOKS_LOG")"
	if grep -F -f <(printf '%s\n' "$ids") <<<"$out" >/dev/null; then
		die "an abandoned row was delivered"
	fi
	info "$abandoned rows abandoned, counted, and not delivered later"

	section "Each replica alone delivers"
	local alone stopped enabled
	for alone in ligo1 ligo2; do
		stopped=ligo2
		[[ "$alone" == ligo2 ]] && stopped=ligo1
		inner_exec "$stopped" systemctl stop ligo
		enabled="$(hooks_count SYSTEM_MAINTENANCE_ENABLED)"
		serve_e2e '^TestServeWebhookMaintenance$' "$alone" "$alone" || die "TestServeWebhookMaintenance failed on $alone"
		hooks_drained
		[[ "$(hooks_count SYSTEM_MAINTENANCE_ENABLED)" == "$((enabled + 3))" ]] || die "$alone alone did not deliver to the three webhooks"
		inner_exec "$stopped" systemctl start ligo
		serve_wait "$stopped"
		info "$alone delivered alone"
	done

	inner_exec hooks cat "$HOOKS_LOG" | inner_exec ligo1 sh -c "cat >'$LIGO1_E2E/hooks.jsonl' && chmod 0644 '$LIGO1_E2E/hooks.jsonl'"
	serve_e2e '^TestServeWebhookFile$' ligo1 ligo2 || die "TestServeWebhookFile failed"
	info "webhooks of ligo serve passed"
}
